// Single-line vector handwriting stroke dictionary normalized to transformGlyphStrokesToPagePoints space:
// Cap top ≈ 38, x-height ≈ 74, baseline ≈ 142, descender ≈ 176.
// Widths scale proportionally so getGlyphHorizontalMetrics() returns realistic horizontal spans.

function arc(cx, cy, rx, ry, startDeg, endDeg, steps = 8) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((startDeg + (endDeg - startDeg) * (i / steps)) * Math.PI) / 180;
    pts.push({
      x: Math.round((cx + rx * Math.cos(a)) * 10) / 10,
      y: Math.round((cy + ry * Math.sin(a)) * 10) / 10,
    });
  }
  return pts;
}

function line(...coords) {
  const pts = [];
  for (let i = 0; i < coords.length; i += 2) {
    pts.push({ x: coords[i], y: coords[i + 1] });
  }
  return pts;
}

