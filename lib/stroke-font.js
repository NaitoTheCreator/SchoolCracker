const CHAR_ALIASES = {
  '’': "'",
  '‘': "'",
  '‚': ',',
  '…': '.',
  '·': '.',
  '•': '*',
};

export function getFallbackStrokeGlyph(ch) {
  if (!ch || ch === ' ' || ch === '\t' || ch === '\n' || ch === '\r') return null;
  const key = CHAR_ALIASES[ch] || ch;
  return STROKE_GLYPHS[key] || null;
}

export function getAllFallbackStrokeChars() {
  return Object.keys(STROKE_GLYPHS);
}
